    fun resolveLanguage(lang: String): String {
        return if (lang.trim().lowercase() in listOf("system", "sistema", "system default", "システム", "システムデフォルト", "")) {
            LanguageManager.getDeviceDefaultLanguage()
        } else {
            lang
        }
    }

    fun get(lang: String, key: String): String {
        val resolved = resolveLanguage(lang)
        val map = when (resolved.trim().lowercase()) {
            "spanish", "español", "es" -> es
            "french", "français", "fr" -> fr
            "german", "deutsch", "de" -> de
            "italian", "italiano", "it" -> it
            "portuguese", "português", "pt" -> pt
            "japanese", "日本語", "ja" -> ja
            else -> en
        }
        return map[key] ?: en[key] ?: key
    }

    fun get(lang: String, key: String, default: String): String {
        val resolved = resolveLanguage(lang)
        val map = when (resolved.trim().lowercase()) {
            "spanish", "español", "es" -> es
            "french", "français", "fr" -> fr
            "german", "deutsch", "de" -> de
            "italian", "italiano", "it" -> it
            "portuguese", "português", "pt" -> pt
            "japanese", "日本語", "ja" -> ja
            else -> en
        }
        return map[key] ?: en[key] ?: default
    }
